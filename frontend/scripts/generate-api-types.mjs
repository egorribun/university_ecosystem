import { mkdir, writeFile, readFile, access } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import path from "node:path"
import openapiTS, { astToString } from "openapi-typescript"
import prettier from "prettier"

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const repoRoot = path.resolve(__dirname, "..", "..")
const fallbackSnapshotPath = path.resolve(
  repoRoot,
  "tests",
  "contracts",
  "snapshots",
  "api_openapi_v1.json"
)

const defaultOrigin =
  process.env.API_ORIGIN || process.env.BACKEND_ORIGIN || "http://localhost:8000"
const configuredPath = process.env.OPENAPI_PATH

let source = process.env.OPENAPI_URL
if (!source) {
  if (configuredPath) {
    source = configuredPath
  } else {
    source = new URL("/api/openapi.json", defaultOrigin).toString()
  }
}

async function loadSchema(input) {
  if (input.startsWith("http://") || input.startsWith("https://")) {
    console.log(`[generate-api-types] Fetching schema from ${input}`)
    try {
      const response = await fetch(input)
      if (!response.ok) {
        throw new Error(
          `Failed to download OpenAPI schema: ${response.status} ${response.statusText}`
        )
      }
      return response.json()
    } catch (error) {
      try {
        await access(fallbackSnapshotPath)
        console.warn(
          "[generate-api-types] Falling back to local snapshot %s because fetching schema failed:",
          fallbackSnapshotPath,
          error
        )
        return loadSchema(fallbackSnapshotPath)
      } catch {
        // If the snapshot is unavailable, rethrow the original error to surface the failure
      }
      throw error
    }
  }

  const resolved = path.isAbsolute(input) ? input : path.resolve(repoRoot, input)
  console.log(`[generate-api-types] Reading schema from ${resolved}`)
  const contents = await readFile(resolved, "utf8")
  return JSON.parse(contents)
}

function sortKeys(obj) {
  if (Array.isArray(obj)) {
    return obj.map(sortKeys)
  } else if (obj !== null && typeof obj === "object") {
    return Object.keys(obj)
      .sort()
      .reduce((acc, key) => {
        acc[key] = sortKeys(obj[key])
        return acc
      }, {})
  }
  return obj
}

async function main() {
  const schema = await loadSchema(source)
  const sortedSchema = sortKeys(schema)
  const ast = await openapiTS(sortedSchema)
  const output = astToString(ast)

  const outputDir = path.resolve(__dirname, "..", "src", "api", "generated")
  await mkdir(outputDir, { recursive: true })
  const outputPath = path.join(outputDir, "schema.ts")

  const header = `/* eslint-disable */\n/* tslint:disable */\n/**\n * This file is auto-generated by scripts/generate-api-types.mjs.\n * Do not edit this file directly.\n */\n`
  const rawContent = header + output
  const prettierConfig = await prettier.resolveConfig(outputPath, {
    editorconfig: true,
  })
  const formattedContent = await prettier.format(rawContent, {
    ...(prettierConfig ?? {}),
    filepath: outputPath,
  })
  await writeFile(outputPath, formattedContent, "utf8")
  console.log(`[generate-api-types] Wrote types to ${path.relative(repoRoot, outputPath)}`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
