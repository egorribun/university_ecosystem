@contextmanager
def _membership(
    schema: SimpleNamespace, event_owner: str, user_owner: str
) -> Iterator[SimpleNamespace]:
    """Create and remove only rows belonging to this acknowledged owned proof."""
    admin = tenant_rls._engine(schema.admin)
    event_id, user_id, attendance_id = uuid4(), uuid4(), uuid4()
    owners = {
        "own": tenant_rls._TENANT_A,
        "foreign": tenant_rls._TENANT_B,
        "null": None,
    }
    identifiers = {"event": event_id, "user": user_id, "attendance": attendance_id}
    starts = datetime(2035, 1, 1, 10, tzinfo=UTC)
    try:
        with admin.begin() as connection:
            # The role is generated by the verified disposable baseline fixture.
            role = schema.ordinary.username
            assert role is not None and role.startswith("tenant_reader_")
            assert role.removeprefix("tenant_reader_").isalnum()
            connection.exec_driver_sql(
                f'GRANT SELECT, DELETE ON public.event_attendance TO "{role}"'
            )
            connection.execute(
                sa.text(
                    "INSERT INTO users(id, email, hashed_password, tenant_id) "
                    "VALUES (:id, :email, :credential, :tenant)"
                ),
                {
                    "id": user_id,
                    "email": f"event-proof-{user_id}@example.invalid",
                    "credential": "!" + uuid4().hex,
                    "tenant": owners[user_owner],
                },
            )
            connection.execute(
                sa.text(
                    "INSERT INTO events(id, title, starts_at, ends_at, tenant_id) "
                    "VALUES (:id, 'Event membership proof', :start, :end, :tenant)"
                ),
                {
                    "id": event_id,
                    "start": starts,
                    "end": starts + timedelta(hours=1),
                    "tenant": owners[event_owner],
                },
            )
            connection.execute(
                sa.text(
                    "INSERT INTO event_attendance(id, event_id, user_id, qr_secret, qr_hmac) "
                    "VALUES (:attendance, :event, :user, 'owned-test', 'owned-test')"
                ),
                identifiers,
            )
        yield SimpleNamespace(**identifiers)
    finally:
        try:
            with admin.begin() as connection:
                connection.execute(
                    sa.text("DELETE FROM event_attendance WHERE id=:attendance"),
                    identifiers,
                )
                connection.execute(
                    sa.text("DELETE FROM events WHERE id=:event"), identifiers
                )
                connection.execute(
                    sa.text("DELETE FROM users WHERE id=:user"), identifiers
                )
        finally:
            admin.dispose()


@asynccontextmanager
async def _ordinary_sessions(
    schema: SimpleNamespace,
) -> AsyncIterator[async_sessionmaker[AsyncSession]]:
    register_tenant_listeners()
    engine = create_async_engine(
        schema.ordinary.set(drivername="postgresql+asyncpg", query={}),
        poolclass=sa.pool.NullPool,
        hide_parameters=True,
        connect_args={"timeout": 5},
    )
    tenant = tenant_id_ctx.set(str(tenant_rls._TENANT_A))
    bypass = bypass_rls_ctx.set(False)
    try:
        yield async_sessionmaker(engine, expire_on_commit=False)
    finally:
        try:
            await engine.dispose()
        finally:
            bypass_rls_ctx.reset(bypass)
            tenant_id_ctx.reset(tenant)


async def _assert_ordinary_boundary(session: AsyncSession) -> None:
    evidence = (
        await session.execute(
            sa.text(
                "SELECT rolsuper, rolbypassrls, "
                "pg_has_role(current_user, 'ue_rls_bypass', 'MEMBER'), "
                "row_security_active('public.events'), row_security_active('public.users'), "
                "row_security_active('public.event_attendance'), "
                "current_setting('app.current_tenant', true), current_setting('transaction_isolation') "
                "FROM pg_roles WHERE rolname=current_user"
            )
        )
    ).one()
    assert tuple(evidence) == (
        False,
        False,
        False,
        True,
        True,
        False,
        str(tenant_rls._TENANT_A),
        "read committed",
    )


@pytest.mark.asyncio
@pytest.mark.parametrize("event_owner", ["own", "foreign", "null"])
@pytest.mark.parametrize("user_owner", ["own", "foreign", "null"])
async def test_event_file_membership_requires_both_rls_visible_parents(
    rls_schema: SimpleNamespace, event_owner: str, user_owner: str
) -> None:
    with _membership(rls_schema, event_owner, user_owner) as row:
        async with _ordinary_sessions(rls_schema) as sessions, sessions() as session:
            await _assert_ordinary_boundary(session)
            # Child-row visibility alone is insufficient: this table has no RLS.
            assert (
                await session.scalar(
                    sa.select(models.EventAttendance.id).where(
                        models.EventAttendance.id == row.attendance
                    )
                )
                == row.attendance
            )
            assert await EventRepository(session).has_current_attendance(
                row.event, row.user
            ) is (event_owner == "own" and user_owner == "own")


@pytest.mark.asyncio
async def test_event_file_membership_observes_separate_committed_cancellation(
    rls_schema: SimpleNamespace,
) -> None:
    with _membership(rls_schema, "own", "own") as row:
        async with _ordinary_sessions(rls_schema) as sessions, sessions() as reader:
            await _assert_ordinary_boundary(reader)
            loaded = await reader.get(models.EventAttendance, row.attendance)
            assert loaded is not None
            repository = EventRepository(reader)
            assert await repository.has_current_attendance(row.event, row.user) is True
            reader_pid = await reader.scalar(sa.text("SELECT pg_backend_pid()"))
            async with sessions() as remover:
                await _assert_ordinary_boundary(remover)
                assert (
                    await remover.scalar(sa.text("SELECT pg_backend_pid()"))
                    != reader_pid
                )
                await remover.execute(
                    sa.delete(models.EventAttendance).where(
                        models.EventAttendance.id == row.attendance
                    )
                )
                assert (
                    await repository.has_current_attendance(row.event, row.user) is True
                )
                await remover.commit()
            # The reader stays in its original READ COMMITTED transaction, with
            # a stale identity-map object. The next scalar query must see removal.
            assert reader.in_transaction()
            assert await reader.get(models.EventAttendance, row.attendance) is loaded
            assert await repository.has_current_attendance(row.event, row.user) is False
            assert bypass_rls_ctx.get() is False
