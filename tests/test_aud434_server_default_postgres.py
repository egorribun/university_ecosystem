def _register_server_default_plugin() -> None:
    """Preload the pinned plugin under the production import name."""
    module_name = "app.core.db.alembic_json_server_defaults"
    plugin_path = os.environ.get("AUD434_SERVER_DEFAULT_PLUGIN_PATH")
    if plugin_path is None:
        plugin_module: Any = importlib.import_module(module_name)
    else:
        importlib.import_module("app.core.db")
        expected_path = Path(plugin_path).resolve()
        plugin_module = sys.modules.get(module_name)
        if plugin_module is None:
            spec = importlib.util.spec_from_file_location(module_name, expected_path)
            assert spec is not None and spec.loader is not None
            plugin_module = importlib.util.module_from_spec(spec)
            sys.modules[module_name] = plugin_module
            try:
                spec.loader.exec_module(plugin_module)
            except BaseException:
                sys.modules.pop(module_name, None)
                raise
        else:
            module_file = getattr(plugin_module, "__file__", None)
            assert module_file is not None
            assert Path(module_file).resolve() == expected_path
    plugin_module.register()


def _flatten_diffs(value: Any) -> Iterator[tuple[Any, ...]]:
    if isinstance(value, tuple) and value and isinstance(value[0], str):
        yield value
    elif isinstance(value, (list, tuple)):
        for child in value:
            yield from _flatten_diffs(child)


