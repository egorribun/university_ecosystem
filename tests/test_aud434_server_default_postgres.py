def test_alembic_check_reports_json_topic_default_drift(
    owned_postgres: owned.OwnedPostgres,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Exercise check on the baseline, drift, then the restored default."""
    assert version("alembic") == "1.20.0"
    assert version("sqlalchemy") == "2.0.54"
    async_url = owned_postgres.url.set(
        drivername="postgresql+asyncpg", query={}
    ).render_as_string(hide_password=False)
    sync_url = owned_postgres.url.set(drivername="postgresql+psycopg", query={})
    monkeypatch.delenv("DATABASE_URL_FILE", raising=False)
    monkeypatch.setenv("DATABASE_URL", async_url)

    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    script_location = os.environ.get("AUD434_SCRIPT_LOCATION")
    if script_location is None:
        env_path = Path(
            os.environ.get(
                "AUD434_ALEMBIC_ENV_PATH", str(PROJECT_ROOT / "alembic" / "env.py")
            )
        ).resolve()
        script_location = str(env_path.parent)
    config.set_main_option("script_location", script_location)
    config.set_main_option("sqlalchemy.url", async_url)
    engine = sa.create_engine(
        sync_url,
        poolclass=sa.pool.NullPool,
        hide_parameters=True,
        connect_args={"connect_timeout": 5},
    )
    try:
        command.upgrade(config, "head")
        with engine.connect() as connection:
            assert (
                MigrationContext.configure(connection).get_current_revision()
                == BASELINE_REVISION
            )
            events_columns = {
                column["name"]: column
                for column in sa.inspect(connection).get_columns(
                    "events", schema="public"
                )
            }
            search_vector = events_columns.get("search_vector", {})
            assert isinstance(search_vector.get("computed"), dict)
            assert search_vector["computed"].get("persisted") is True

        # This is the real Alembic check through env.py and SQLAlchemy's PostgreSQL
        # reflection/comparator path, including native Computed defaults, against
        # the exact current model and baseline.
        command.check(config)

        with engine.begin() as connection:
            connection.execute(
                sa.text(
                    "ALTER TABLE public.push_subscriptions "
                    "ALTER COLUMN topics SET DEFAULT '[\"aud434-drift\"]'::json"
                )
            )

        try:
            with pytest.raises(AutogenerateDiffsDetected) as detected:
                command.check(config)
            assert any(
                len(diff) >= 4
                and diff[0] == "modify_default"
                and tuple(diff[2:4]) == ("push_subscriptions", "topics")
                for diff in _flatten_diffs(detected.value.diffs)
            ), detected.value.diffs
        finally:
            with engine.begin() as connection:
                connection.execute(
                    sa.text(
                        "ALTER TABLE public.push_subscriptions "
                        "ALTER COLUMN topics SET DEFAULT '[]'::json"
                    )
                )

        command.check(config)
    finally:
        engine.dispose()
